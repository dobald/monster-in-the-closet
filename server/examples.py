"""Example photos for thrift-list pieces, so people know what to look for on the rack.

Generated by Muse Image (text-to-image) as a second-hand piece in good condition, laid
flat and shot from above: the same view as the user's own scans. They are clearly
labelled as AI examples in the app, not photos of real listings or brands. Each one is
generated once per piece (name, colours, category) and cached on disk; fixture mode only
serves ones already made.
"""

from __future__ import annotations

import asyncio
import io

from closet import config, models

from .cache import sha256
from .settings import Settings

EXAMPLE_VERSION = "example1"
EXAMPLE_WIDTH = 960
POSE = {
    "top": "sleeves laid out naturally",
    "outerwear": "buttons or zip done up, sleeves laid out naturally",
    "bottom": "laid straight with the full length visible",
    "dress": "laid straight with the full length visible",
}


def example_prompt(piece: dict) -> str:
    name = piece["name"].strip()
    colors = [c for c in piece.get("colors", []) if c.lower() not in name.lower()]
    what = " ".join(filter(None, [" or ".join(colors[:1]), name.lower()]))
    return (f"Photo of one second-hand {what} in good condition, laid flat on a light wooden floor and shot from "
            f"directly above in soft natural light, {POSE.get(piece.get('category', ''), 'laid out neatly')}. "
            "Realistic phone photo. No people, no text, no logos, no brand labels visible, nothing else in frame.")


class Examples:
    def __init__(self, settings: Settings):
        self.settings = settings
        self.dir = settings.var_dir / "examples"
        self.dir.mkdir(parents=True, exist_ok=True)
        self._inflight: dict[str, asyncio.Future] = {}

    @staticmethod
    def key(piece: dict) -> str:
        colors = ",".join(sorted(c.lower() for c in piece.get("colors", [])))
        return sha256(f"{EXAMPLE_VERSION}:{config.IMAGE_MODEL}:{piece['name'].lower()}:{colors}:{piece.get('category')}"
                      .encode())[:20]

    def url(self, piece: dict) -> str | None:
        """The example's URL if it has been made already."""
        k = self.key(piece)
        return f"/api/examples/{k}.jpg" if (self.dir / f"{k}.jpg").exists() else None

    async def ensure(self, piece: dict) -> dict:
        """Return the example, generating it in live mode. {url, cached, reason}."""
        if url := self.url(piece):
            return {"url": url, "cached": True, "reason": None}
        if not self.settings.live:
            return {"url": None, "cached": False, "reason": "Example photos are made in live mode."}
        k = self.key(piece)
        if k not in self._inflight:  # three cards asking at once still cost one call per piece
            self._inflight[k] = asyncio.ensure_future(self._make(k, piece))
        try:
            return await asyncio.shield(self._inflight[k])
        finally:
            if self._inflight.get(k) is not None and self._inflight[k].done():
                self._inflight.pop(k, None)

    async def _make(self, k: str, piece: dict) -> dict:
        img, status = await asyncio.to_thread(models.generate_image, example_prompt(piece))
        if img is None:
            return {"url": None, "cached": False, "reason": status}
        if img.width > EXAMPLE_WIDTH:
            img = img.resize((EXAMPLE_WIDTH, round(img.height * EXAMPLE_WIDTH / img.width)))
        buf = io.BytesIO()
        img.save(buf, format="JPEG", quality=85)
        (self.dir / f"{k}.jpg").write_bytes(buf.getvalue())
        return {"url": f"/api/examples/{k}.jpg", "cached": False, "reason": None}
